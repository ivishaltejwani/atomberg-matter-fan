#!/usr/bin/env python3
"""Mac side of the fan's WiFi dev link (sketches/atomberg_matter/devlink.h). Replaces the serial cable.

  devlink.py keygen               make the OTA signing key (keys/, never shared) and the public key the
                                  firmware is built with (sketches/atomberg_matter/ota_pubkey.h). Once.
  devlink.py serve [--bin PATH]   run the server and the dashboard (http://localhost:8090). Leave it running.
             [--legacy]           also answer pre-signing firmware (/fw.sha); only for the one-time migration
  devlink.py send CMD [CMD ...]   send command lines to the fan through the running server,
             [--listen S]         then print the fan's log for S seconds (default 3)
  devlink.py tail                 follow logs/devlink.log

OTA: the fan polls /fw.manifest every 30 s. The manifest (version, length, SHA-256 of fw.bin) is signed
here with the private key; the fan checks the signature against its built-in public key and only installs
newer versions. So the LAN side (:8070) only ever serves signed, public data. Rebuilding the sketch or
uploading a .bin in the dashboard is enough; the newest of the two is served.

The dashboard and the command port listen on 127.0.0.1 only. The fan accepts only read-only commands
over the network anyway; anything that changes it needs the serial cable.
"""
import argparse
import hashlib
import http.server
import json
import os
import re
import socket
import struct
import sys
import threading
import time

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
DEFAULT_BIN = os.path.join(ROOT, "build", "atomberg_matter", "atomberg_matter.ino.bin")
UPLOADS = os.path.join(ROOT, "uploads")
LOG = os.path.join(ROOT, "logs", "devlink.log")
KEY = os.path.join(ROOT, "keys", "ota_signing_key.pem")
PUBKEY_H = os.path.join(ROOT, "sketches", "atomberg_matter", "ota_pubkey.h")
DASHBOARD_HTML = os.path.join(os.path.dirname(os.path.abspath(__file__)), "devlink_dashboard.html")
HTTP_PORT, LOG_PORT, FAN_CMD_PORT, CONTROL_PORT, DASHBOARD_PORT = 8070, 8071, 8072, 8073, 8090
SLOT_SIZE = 0x1F0000  # app0/app1 in partitions.csv
APP_DESC_MAGIC = 0xABCD5432
ESP32C3_CHIP_ID = 5
MANIFEST_MAGIC = b"ATOMOTA1"


# ---------- keys and signing ----------

def keygen(force):
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric import ec
    if os.path.exists(KEY) and not force:
        sys.exit(f"{KEY} already exists. Fans built with it only accept updates signed by it; "
                 "--force makes a new key (then every fan needs one serial flash with the new firmware).")
    key = ec.generate_private_key(ec.SECP256R1())
    os.makedirs(os.path.dirname(KEY), exist_ok=True)
    fd = os.open(KEY, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                  serialization.NoEncryption()))
    write_pubkey_header(key)
    print(f"private key: {KEY}  (keep it secret and backed up; it is gitignored)")
    print(f"public key:  {PUBKEY_H}  (rebuild + flash the firmware once over serial so the fan trusts it)")


def load_key():
    from cryptography.hazmat.primitives import serialization
    with open(KEY, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)


def write_pubkey_header(key):
    from cryptography.hazmat.primitives import serialization
    pub = key.public_key().public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
    rows = ",\n".join("  " + ", ".join(f"0x{b:02x}" for b in pub[i:i + 13]) for i in range(0, len(pub), 13))
    with open(PUBKEY_H, "w") as f:
        f.write("// OTA signing public key (P-256, uncompressed), generated by tools/devlink.py keygen.\n"
                "// The fan only installs firmware whose manifest is signed by the matching private key.\n"
                "#pragma once\n#include <stdint.h>\n"
                f"static const uint8_t OTA_PUBKEY[65] = {{\n{rows}}};\n")


def check_image(data):
    """Reject anything that isn't an ESP32-C3 app image that fits an OTA slot."""
    if len(data) > SLOT_SIZE:
        raise ValueError(f"image is {len(data)} bytes, bigger than the {SLOT_SIZE}-byte OTA slot")
    if len(data) < 256 or data[0] != 0xE9:
        raise ValueError("not an ESP app image (use the .ino.bin, not the merged or bootloader bin)")
    if struct.unpack_from("<H", data, 12)[0] != ESP32C3_CHIP_ID:
        raise ValueError("image is not built for ESP32-C3")
    if struct.unpack_from("<I", data, 32)[0] != APP_DESC_MAGIC:
        raise ValueError("no app description in image")


def app_sha(data):
    """app_elf_sha256 from the image's esp_app_desc_t (the value the fan reports in its heartbeat)."""
    return data[176:208].hex()


def make_manifest(key, data, version):
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import ec
    from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature
    body = MANIFEST_MAGIC + struct.pack("<II", version, len(data)) + hashlib.sha256(data).digest()
    r, s = decode_dss_signature(key.sign(body, ec.ECDSA(hashes.SHA256())))
    return body + r.to_bytes(32, "big") + s.to_bytes(32, "big")


class Firmware:
    """The build being offered: the newest of the sketch build output and the latest dashboard upload."""

    def __init__(self, key, pinned):
        self.key, self.pinned = key, pinned
        self.lock = threading.Lock()
        self.cache_key = None
        self.info = {}

    def candidates(self):
        if self.pinned:
            return [self.pinned]
        files = [DEFAULT_BIN]
        if os.path.isdir(UPLOADS):
            files += [os.path.join(UPLOADS, f) for f in os.listdir(UPLOADS) if f.endswith(".bin")]
        return [f for f in files if os.path.exists(f)]

    def current(self):
        with self.lock:
            files = self.candidates()
            if not files:
                raise ValueError("no firmware built or uploaded yet")
            path = max(files, key=os.path.getmtime)
            mtime = os.path.getmtime(path)
            if self.cache_key != (path, mtime):
                with open(path, "rb") as f:
                    data = f.read()
                check_image(data)
                version = int(mtime)  # newer build or upload = higher version
                self.info = {"path": path, "name": os.path.relpath(path, ROOT), "data": data, "version": version,
                             "size": len(data), "app_sha": app_sha(data),
                             "manifest": make_manifest(self.key, data, version) if self.key else None}
                self.cache_key = (path, mtime)
                log_line(f"devlink: offering {self.info['name']} v{version} (app {self.info['app_sha'][:8]}, "
                         f"{len(data)} bytes)")
            return self.info


# ---------- log ----------

log_lock = threading.Lock()


def log_line(text):
    stamp = time.strftime("%H:%M:%S")
    with log_lock, open(LOG, "a") as f:
        for ln in text.splitlines():
            out = f"[{stamp}] {ln}"
            print(out, flush=True)
            f.write(out + "\n")


# ---------- server ----------

HB = re.compile(r"hb sha=(\w+) up=(\d+)s heap=(\d+)(?: ota=v(\d+))?")


def serve(bin_path, legacy):
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    key = load_key() if os.path.exists(KEY) else None
    if not key:
        log_line("devlink: no signing key (run 'devlink.py keygen'): OTA is off, logs/commands still work")
    fw = Firmware(key, bin_path)
    fan = {"addr": None, "seen": 0, "sha": None, "up": None, "heap": None, "ota": None}

    udp = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    udp.bind(("0.0.0.0", LOG_PORT))

    def send_to_fan(line):
        if not fan["addr"]:
            log_line("devlink: no fan heard yet, command dropped")
            return False
        udp.sendto(line.encode() + b"\n", (fan["addr"], FAN_CMD_PORT))  # from :8071 = a reply to the fan
        log_line(f"> {line}")
        return True

    class OtaHandler(http.server.BaseHTTPRequestHandler):
        """LAN side: only signed, public data."""

        def do_GET(self):
            try:
                info = fw.current()
                if self.path == "/fw.manifest" and info["manifest"]:
                    body = info["manifest"]
                elif self.path == "/fw.bin" and info["manifest"]:
                    body = info["data"]
                    log_line(f"devlink: fan {self.client_address[0]} is downloading v{info['version']} "
                             f"({len(body)} bytes)")
                elif self.path == "/fw.sha" and legacy:
                    body = info["app_sha"].encode()
                elif self.path == "/fw.bin" and legacy:
                    body = info["data"]
                    log_line(f"devlink: LEGACY unsigned download by {self.client_address[0]}")
                else:
                    self.send_error(404)
                    return
            except (OSError, ValueError) as e:
                log_line(f"devlink: not serving {self.path}: {e}")
                self.send_error(503)
                return
            self.send_response(200)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *args):
            pass

    class DashboardHandler(http.server.BaseHTTPRequestHandler):
        """127.0.0.1 only: the web page and its API."""

        def reply(self, code, body, ctype="application/json"):
            if isinstance(body, (dict, list)):
                body = json.dumps(body).encode()
            elif isinstance(body, str):
                body = body.encode()
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(body)

        def same_origin(self):
            # Block other web pages in the browser from driving the API (CSRF / DNS rebinding).
            host = self.headers.get("Host", "")
            origin = self.headers.get("Origin")
            local = (f"localhost:{DASHBOARD_PORT}", f"127.0.0.1:{DASHBOARD_PORT}")
            return host in local and (origin is None or origin in tuple("http://" + h for h in local))

        def do_GET(self):
            if not self.same_origin():
                return self.reply(403, {"error": "forbidden"})
            if self.path == "/":
                with open(DASHBOARD_HTML, "rb") as f:
                    return self.reply(200, f.read(), "text/html; charset=utf-8")
            if self.path == "/api/state":
                try:
                    info = fw.current()
                    offered = {k: info[k] for k in ("name", "version", "size", "app_sha")}
                    offered["error"] = None
                except (OSError, ValueError) as e:
                    offered = {"error": str(e)}
                age = time.time() - fan["seen"] if fan["seen"] else None
                return self.reply(200, {"fan": {**fan, "age": age}, "offered": offered, "signing": bool(key)})
            if self.path.startswith("/api/log"):
                m = re.search(r"since=(\d+)", self.path)
                since = int(m.group(1)) if m else -1
                size = os.path.getsize(LOG) if os.path.exists(LOG) else 0
                start = max(0, size - 32768) if since < 0 or since > size else since
                with open(LOG, "rb") as f:
                    f.seek(start)
                    text = f.read(262144).decode(errors="replace")
                return self.reply(200, {"offset": start + len(text.encode()), "text": text})
            self.reply(404, {"error": "not found"})

        def do_POST(self):
            if not self.same_origin():
                return self.reply(403, {"error": "forbidden"})
            length = int(self.headers.get("Content-Length", 0))
            if length > SLOT_SIZE + 4096:
                return self.reply(413, {"error": "too large"})
            body = self.rfile.read(length)
            if self.path == "/api/cmd":
                line = json.loads(body or b"{}").get("line", "").strip()
                if not line or "\n" in line:
                    return self.reply(400, {"error": "one command line please"})
                return self.reply(200, {"sent": send_to_fan(line)})
            if self.path == "/api/upload":
                if not key:
                    return self.reply(400, {"error": "no signing key: run devlink.py keygen first"})
                try:
                    check_image(body)
                except ValueError as e:
                    return self.reply(400, {"error": str(e)})
                name = re.sub(r"[^A-Za-z0-9._-]", "_", self.headers.get("X-Filename", "upload.bin"))[-60:]
                os.makedirs(UPLOADS, exist_ok=True)
                path = os.path.join(UPLOADS, time.strftime("%Y%m%d-%H%M%S-") + name)
                with open(path, "wb") as f:
                    f.write(body)
                log_line(f"devlink: uploaded {os.path.relpath(path, ROOT)} (app {app_sha(body)[:8]})")
                info = fw.current()
                return self.reply(200, {"offered": info["name"], "version": info["version"]})
            self.reply(404, {"error": "not found"})

        def log_message(self, *args):
            pass

    for handler, addr in ((OtaHandler, ("0.0.0.0", HTTP_PORT)), (DashboardHandler, ("127.0.0.1", DASHBOARD_PORT))):
        httpd = http.server.ThreadingHTTPServer(addr, handler)
        threading.Thread(target=httpd.serve_forever, daemon=True).start()

    ctl = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    ctl.bind(("127.0.0.1", CONTROL_PORT))

    def forward_commands():
        while True:
            data, _ = ctl.recvfrom(2048)
            for line in data.decode(errors="replace").splitlines():
                if line.strip():
                    send_to_fan(line.strip())

    threading.Thread(target=forward_commands, daemon=True).start()
    try:
        fw.current()
    except (OSError, ValueError) as e:
        log_line(f"devlink: nothing to offer yet ({e})")
    log_line(f"devlink: OTA on :{HTTP_PORT} ({'signed' if key else 'off'}{', +legacy' if legacy else ''}), "
             f"logs on udp :{LOG_PORT}, dashboard http://localhost:{DASHBOARD_PORT}")
    while True:
        data, (ip, _) = udp.recvfrom(4096)
        if fan["addr"] != ip:
            fan["addr"] = ip
            log_line(f"devlink: fan at {ip}")
        fan["seen"] = time.time()
        text = data.decode(errors="replace")
        for m in HB.finditer(text):
            fan.update(sha=m.group(1), up=int(m.group(2)), heap=int(m.group(3)),
                       ota=int(m.group(4)) if m.group(4) else None)
        log_line(text.rstrip("\n"))


# ---------- client helpers ----------

def send(cmds, listen):
    start = os.path.getsize(LOG) if os.path.exists(LOG) else 0
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    for c in cmds:
        s.sendto(c.encode() + b"\n", ("127.0.0.1", CONTROL_PORT))
    time.sleep(listen)
    with open(LOG) as f:
        f.seek(start)
        sys.stdout.write(f.read())


def tail():
    with open(LOG) as f:
        f.seek(0, os.SEEK_END)
        while True:
            ln = f.readline()
            if ln:
                sys.stdout.write(ln)
                sys.stdout.flush()
            else:
                time.sleep(0.2)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("keygen")
    p.add_argument("--force", action="store_true")
    p = sub.add_parser("serve")
    p.add_argument("--bin", help="always offer this file instead of the newest build/upload")
    p.add_argument("--legacy", action="store_true")
    p = sub.add_parser("send")
    p.add_argument("lines", nargs="+")
    p.add_argument("--listen", type=float, default=3)
    sub.add_parser("tail")
    a = ap.parse_args()
    if a.cmd == "keygen":
        keygen(a.force)
    elif a.cmd == "serve":
        serve(a.bin, a.legacy)
    elif a.cmd == "send":
        send(a.lines, a.listen)
    else:
        tail()
